export function createGenerationService(
  host: CoreHost,
  deps: GenerationServiceDeps = {},
): GenerationService {
  const { repository } = host;
  const logger = host.logger ?? noopLogger;
  const assets = deps.assets ?? createAssetStore(host);
  const tasks = deps.tasks ?? createTaskService(host);

  /** Upstream `getProviderAdapter()`, reduced to the two ports that own it. */
  async function resolveProviderAdapter(scope: ProviderScope) {
    const resolved = await host.provider.resolve(scope);
    const adapter = new OpenAICompatibleAdapter(resolved.baseUrl, resolved.apiKey, logger);
    const provider: ProviderContext = { models: resolved.models };

    return { provider, adapter };
  }

  /**
   * Upstream `prisma.productAsset.findMany({ where: { id: { in: ids } } })`.
   * The Repository port exposes per-id reads instead of an id-set filter, so the
   * requested order is preserved (upstream returned DB order, which nothing
   * downstream depended on — `mergeReferenceAssets` re-ranks by primary asset).
   * Like upstream, this is NOT project-scoped.
   */
  async function resolveReferenceAssets(referenceAssetIds: string[]): Promise<ProductAsset[]> {
    if (!referenceAssetIds.length) {
      return [];
    }

    const uniqueIds = [...new Set(referenceAssetIds)];
    const found = await Promise.all(uniqueIds.map((id) => repository.asset.get(id)));

    return found.filter((asset): asset is ProductAsset => Boolean(asset));
  }

  /**
   * Upstream `persistSectionVersion`: read the last `versionNumber`, mark every
   * sibling inactive, then create the next active version.
   */
  async function persistSectionVersion(params: {
    sectionId: string;
    imageAssetId: string;
    promptSnapshot: string;
    copySnapshot: string;
  }) {
    const versionNumber = await repository.version.nextVersionNumber(params.sectionId);

    const created = await repository.version.create({
      sectionId: params.sectionId,
      versionNumber,
      promptSnapshot: { prompt: params.promptSnapshot },
      copySnapshot: { copy: params.copySnapshot },
      imageAssetId: params.imageAssetId,
    });

    // `CreateVersionInput` carries no `isActive`, so the port cannot express
    // "deactivate siblings + activate this one" in `create` alone. Upstream's
    // invariant is enforced through `setActive` whenever `create` did not
    // already return an active version.
    if (!created.isActive) {
      return repository.version.setActive(params.sectionId, created.id);
    }

    return created;
  }

  async function listSectionVersions(sectionId: string): Promise<SectionVersionWithAsset[]> {
    const versions = await repository.version.list(sectionId);
    const ordered = [...versions].sort((a, b) => b.versionNumber - a.versionNumber);

    return Promise.all(
      ordered.map(async (version) => ({
        ...version,
        imageAsset: version.imageAssetId ? await repository.asset.get(version.imageAssetId) : null,
      })),
    );
  }

  async function activateSectionVersion(sectionId: string, versionId: string): Promise<SectionVersionWithAsset | null> {
    const version = await repository.version.get(versionId);

    if (!version || version.sectionId !== sectionId) {
      throw new Error("Version not found.");
    }

    // Upstream: `updateMany({ isActive: false })` + `update({ isActive: true })`.
    await repository.version.setActive(sectionId, versionId);

    await repository.section.update(sectionId, {
      currentImageAssetId: version.imageAssetId ?? null,
      status: "SUCCESS",
    });

    const activated = await repository.version.get(versionId);
    if (!activated) {
      return null;
    }

    return {
      ...activated,
      imageAsset: activated.imageAssetId ? await repository.asset.get(activated.imageAssetId) : null,
    };
  }

  async function generateSectionImageInternal(
    projectId: string,
    sectionId: string,
    options?: {
      preferredModelId?: string | null;
      referenceAssetIds?: string[];
      regenerate?: boolean;
      onTaskCreated?: (taskId: string) => void | Promise<void>;
    },
  ): Promise<SectionImageGenerationResult> {
    const project = await repository.project.getDetail(projectId);

    const section = await repository.section.get(sectionId);

    if (!project) {
      throw new Error("Project not found.");
    }

    if (!section || section.projectId !== projectId) {
      throw new Error("Section not found.");
    }

    const projectAssets = orderProjectAssets(project.assets);

    const runningTask = await tasks.findRecentRunningTask({
      projectId,
      sectionId,
      taskType: options?.regenerate ? "REGENERATE" : "GENERATE",
      maxAgeMinutes: 20,
    });
    if (runningTask) {
      throw new Error("当前模块图仍在生成中，请等待这一轮完成后再试。");
    }

    const task = await tasks.createTask({
      projectId,
      sectionId,
      taskType: options?.regenerate ? "REGENERATE" : "GENERATE",
      inputPayload: {
        referenceAssetIds: options?.referenceAssetIds ?? [],
        regenerate: Boolean(options?.regenerate),
      },
    });
    const taskSignal = tasks.registerTaskAbortController(task.id);

    try {
      await options?.onTaskCreated?.(task.id);
      await repository.section.update(sectionId, { status: "GENERATING" });
      await tasks.assertTaskNotCanceled(task.id);
      assertNotCanceled(taskSignal);

      const { provider, adapter } = await resolveProviderAdapter({
        projectId,
        sectionId,
        operation: options?.regenerate ? "regenerate_section_image" : "generate_section_image",
      });
      const generationSettings = getGenerationSettings(project);
      const visualStyleGuide = getProjectVisualStyleGuide(project);
      const generationRequirements = readGenerationRequirements(project.analysis?.normalizedResult);
      const sectionAspectRatio = getSectionAspectRatio(section, generationSettings.imageAspectRatio);
      const outputSize = getOutputSize(sectionAspectRatio);
      const modelCandidates = buildImageModelCandidates(provider, options);
      const selectedModel = modelCandidates[0] ?? null;
      const explicitReferenceAssets = await resolveReferenceAssets(options?.referenceAssetIds ?? []);
      const effectiveReferenceAssets = mergeReferenceAssets(
        projectAssets as AssetRecord[],
        explicitReferenceAssets as AssetRecord[],
      );
      const referenceImages = await Promise.all(
        effectiveReferenceAssets.map((asset) => assetToDataUrl(assets, asset)),
      );
      await tasks.assertTaskNotCanceled(task.id);
      assertNotCanceled(taskSignal);

      const basePrompt = options?.regenerate
        ? buildRegenerationPrompt(
            section,
            effectiveReferenceAssets as ProductAsset[],
            sectionAspectRatio,
            generationSettings.contentLanguage,
            generationRequirements,
          )
        : buildSectionImagePrompt(
            section,
            effectiveReferenceAssets as ProductAsset[],
            sectionAspectRatio,
            generationSettings.contentLanguage,
            generationRequirements,
          );
      const prompt = await buildVisualPromptWithAgent({
        provider,
        adapter,
        mode: "ecommerce_section",
        title: section.title,
        goal: section.goal,
        copy: section.copy,
        basePrompt,
        aspectRatio: sectionAspectRatio,
        contentLanguage: generationSettings.contentLanguage,
        referenceImages,
        referenceAssets: effectiveReferenceAssets as ProductAsset[],
        productContext: project.analysis?.normalizedResult ?? project.modelSnapshot ?? null,
        visualStyleGuide,
        projectId,
        sectionId,
        operation: options?.regenerate ? "visual_prompt_agent_regenerate_section" : "visual_prompt_agent_generate_section",
        signal: taskSignal,
      });
      await tasks.assertTaskNotCanceled(task.id);
      assertNotCanceled(taskSignal);

      let imageAsset;
      let version;
      let usedModel: string;
      let generationMode: GenerationMode;

      try {
        if (!selectedModel) {
          throw new Error("当前 Provider 没有识别到可用于真实图片生成的模型。");
        }

        const generation = await generateWithFallback({
          adapter,
          candidateModels: modelCandidates,
          prompt,
          size: outputSize,
          aspectRatio: sectionAspectRatio,
          referenceImages,
          projectId,
          sectionId,
          operation: options?.regenerate ? "regenerate_section_image" : "generate_section_image",
          signal: taskSignal,
        });
        await tasks.assertTaskNotCanceled(task.id);
        assertNotCanceled(taskSignal);

        imageAsset = await assets.saveGeneratedImage({
          projectId,
          sectionId,
          prompt,
          source: generation.generated,
          metadata: {
            mode: "image_api",
            usedModel: generation.model,
            sourceReferenceAssetIds: effectiveReferenceAssets.map((asset) => asset.id),
            primaryReferenceAssetId: effectiveReferenceAssets[0]?.id ?? null,
          },
        });
        await tasks.assertTaskNotCanceled(task.id);
        assertNotCanceled(taskSignal);

        usedModel = generation.model;
        generationMode = "image_api";
      } catch (error) {
        if (isTaskCanceledError(error)) throw error;
        if (!generationSettings.allowSvgFallback) {
          const detail = error instanceof Error ? error.message : "Unknown image generation error";
          if (/monthly spending limit|spending limit|billing|quota/i.test(detail)) {
            throw new Error("当前 API Key 的图片生成额度已用尽。请前往代理商控制台提高或移除月度限额，或更换可用的 API Key。");
          }
          if (isTransientImageNetworkFailure(detail)) {
            throw new Error(buildTransientImageNetworkMessage(detail));
          }
          const summary = summarizeProviderImageFailure(detail, "generate");
          throw new Error(
            `当前 Provider 没有可用的真实图片生成端点。请前往“模型服务配置”页更换支持图片生成的 Provider，或在规划页手动开启“允许 SVG 兜底预览”。原因摘要：${summary}`,
          );
        }

        const fallback = await generateSvgFallback({
          section,
          adapter,
          provider,
          assets,
          referenceAssets: effectiveReferenceAssets,
          aspectRatio: sectionAspectRatio,
          contentLanguage: generationSettings.contentLanguage,
          signal: taskSignal,
        });
        await tasks.assertTaskNotCanceled(task.id);
        assertNotCanceled(taskSignal);

        imageAsset = await assets.saveGeneratedImage({
          projectId,
          sectionId,
          prompt,
          source: {
            svgText: fallback.svgText,
            mimeType: "image/svg+xml",
          },
          metadata: {
            mode: "svg_fallback",
            usedModel: fallback.model,
            layout: fallback.layout,
            sourceReferenceAssetIds: effectiveReferenceAssets.map((asset) => asset.id),
            primaryReferenceAssetId: effectiveReferenceAssets[0]?.id ?? null,
            imageApiError: error instanceof Error ? error.message : "Unknown image api error",
          },
        });
        await tasks.assertTaskNotCanceled(task.id);
        assertNotCanceled(taskSignal);

        usedModel = fallback.model;
        generationMode = "svg_fallback";
      }

      version = await persistSectionVersion({
        sectionId,
        imageAssetId: imageAsset.id,
        promptSnapshot: prompt,
        copySnapshot: section.copy,
      });

      await repository.section.update(sectionId, {
        status: "SUCCESS",
        currentImageAssetId: imageAsset.id,
      });

      await repository.project.update(projectId, {
        status: "EDITING",
      });

      await tasks.completeTask(task.id, {
        imageAssetId: imageAsset.id,
        versionId: version.id,
        usedModel,
        generationMode,
        sourceReferenceAssetIds: effectiveReferenceAssets.map((asset) => asset.id),
      });

      return { imageAsset, version, usedModel, generationMode };
    } catch (error) {
      await repository.section.update(sectionId, {
        status: isTaskCanceledError(error) ? (section.currentImageAssetId ? "SUCCESS" : "IDLE") : "FAILED",
      });

      if (!isTaskCanceledError(error)) {
        await tasks.failTask(task.id, error instanceof Error ? error.message : "Image generation failed");
      }
      throw error;
    } finally {
      tasks.releaseTaskAbortController(task.id);
    }
  }

  async function generateSectionImage(
    projectId: string,
    sectionId: string,
    preferredModelId?: string | null,
    referenceAssetIds?: string[],
    onTaskCreated?: (taskId: string) => void | Promise<void>,
  ) {
    return generateSectionImageInternal(projectId, sectionId, {
      preferredModelId,
      referenceAssetIds,
      regenerate: false,
      onTaskCreated,
    });
  }

  async function regenerateSectionImage(
    projectId: string,
    sectionId: string,
    preferredModelId?: string | null,
    referenceAssetIds?: string[],
    onTaskCreated?: (taskId: string) => void | Promise<void>,
  ) {
    return generateSectionImageInternal(projectId, sectionId, {
      preferredModelId,
      referenceAssetIds,
      regenerate: true,
      onTaskCreated,
    });
  }

  async function editSectionImage(
    projectId: string,
    sectionId: string,
    options?: EditSectionImageOptions,
  ): Promise<SectionImageEditResult> {
    const project = await repository.project.getDetail(projectId);

    const section = await repository.section.get(sectionId);

    if (!project) {
      throw new Error("Project not found.");
    }

    if (!section || section.projectId !== projectId) {
      throw new Error("Section not found.");
    }

    // Upstream `include: { currentImageAsset: true }`.
    const currentImageAsset = section.currentImageAssetId
      ? await repository.asset.get(section.currentImageAssetId)
      : null;

    if (!currentImageAsset) {
      throw new Error("当前模块还没有可编辑的底图，请先生成一张模块图。");
    }

    const { provider, adapter } = await resolveProviderAdapter({
      projectId,
      sectionId,
      operation: "edit_section_image",
    });
    const generationSettings = getGenerationSettings(project);
    const visualStyleGuide = getProjectVisualStyleGuide(project);
    const generationRequirements = readGenerationRequirements(project.analysis?.normalizedResult);
    const sectionAspectRatio = getSectionAspectRatio(section, generationSettings.imageAspectRatio);
    const outputSize = getOutputSize(sectionAspectRatio);
    const modelCandidates = buildImageModelCandidates(provider, {
      preferredModelId: options?.preferredModelId,
      edit: true,
      regenerate: true,
    });
    const selectedModel = modelCandidates[0] ?? null;
    const explicitReferenceAssets = await resolveReferenceAssets(options?.referenceAssetIds ?? []);
    const productReferenceAssets = mergeReferenceAssets(
      orderProjectAssets(project.assets) as AssetRecord[],
      explicitReferenceAssets as AssetRecord[],
    );
    const baseImage = await assetToDataUrl(assets, currentImageAsset as AssetRecord);
    const referenceImages = await Promise.all(
      productReferenceAssets
        .filter((asset) => asset.id !== section.currentImageAssetId)
        .map((asset) => assetToDataUrl(assets, asset)),
    );
    const editMode = options?.editMode ?? "repaint";
    const effectiveContentLanguage = editMode === "translate" ? normalizeContentLanguage(options?.targetLanguage) : generationSettings.contentLanguage;
    const runningTask = await tasks.findRecentRunningTask({
      projectId,
      sectionId,
      taskType: "REGENERATE",
      maxAgeMinutes: 20,
    });
    if (runningTask) {
      throw new Error("当前模块图仍在重绘或增强中，请等待这一轮完成后再试。");
    }

    const task = await tasks.createTask({
      projectId,
      sectionId,
      taskType: "REGENERATE",
      inputPayload: {
        mode: "edit_image",
        editMode,
        targetLanguage: editMode === "translate" ? effectiveContentLanguage : undefined,
        model: selectedModel,
        modelCandidates,
        baseImageAssetId: section.currentImageAssetId,
        referenceAssetIds: options?.referenceAssetIds ?? [],
        effectiveReferenceAssetIds: productReferenceAssets.map((asset) => asset.id),
        allowSvgFallback: generationSettings.allowSvgFallback,
      },
    });

    await repository.section.update(sectionId, { status: "GENERATING" });

    // NOTE(dsh-port): upstream `editSectionImage` never called
    // `registerTaskAbortController` / `assertTaskNotCanceled` and never threaded
    // a signal, so this path is NOT cooperatively cancellable (unlike
    // generate/regenerate) and there is no `releaseTaskAbortController` in a
    // `finally`. Preserved as-is rather than silently changed; flagged for the
    // parent to decide.
    try {
      const basePrompt = buildImageEditPrompt(
        section,
        productReferenceAssets as ProductAsset[],
        editMode,
        sectionAspectRatio,
        effectiveContentLanguage,
        generationRequirements,
      );
      const prompt = await buildVisualPromptWithAgent({
        provider,
        adapter,
        mode: "image_edit",
        title: section.title,
        goal: section.goal,
        copy: section.copy,
        basePrompt,
        aspectRatio: sectionAspectRatio,
        contentLanguage: effectiveContentLanguage,
        referenceImages: [baseImage, ...referenceImages],
        referenceAssets: productReferenceAssets as ProductAsset[],
        productContext: project.analysis?.normalizedResult ?? project.modelSnapshot ?? null,
        visualStyleGuide,
        projectId,
        sectionId,
        operation: editMode === "translate" ? "visual_prompt_agent_translate_section" : editMode === "enhance" ? "visual_prompt_agent_enhance_section" : "visual_prompt_agent_repaint_section",
      });

      let imageAsset;
      let version;
      let usedModel: string;
      let generationMode: GenerationMode;

      try {
        if (!selectedModel) {
          throw new Error("当前 Provider 没有识别到可用于真实图片编辑的模型。");
        }

        const generation = await editWithFallback({
          adapter,
          candidateModels: modelCandidates,
          prompt,
          image: baseImage,
          size: outputSize,
          aspectRatio: sectionAspectRatio,
          referenceImages,
          projectId,
          sectionId,
          operation: editMode === "translate" ? "translate_section_image" : editMode === "enhance" ? "enhance_section_image" : "repaint_section_image",
        });

        imageAsset = await assets.saveGeneratedImage({
          projectId,
          sectionId,
          prompt,
          source: generation.generated,
          metadata: {
            mode: "image_api",
            usedModel: generation.model,
            editMode,
            targetLanguage: editMode === "translate" ? effectiveContentLanguage : undefined,
            baseImageAssetId: section.currentImageAssetId,
            sourceReferenceAssetIds: productReferenceAssets.map((asset) => asset.id),
            primaryReferenceAssetId: productReferenceAssets[0]?.id ?? null,
          },
        });

        usedModel = generation.model;
        generationMode = "image_api";
      } catch (error) {
        if (!generationSettings.allowSvgFallback) {
          const detail = error instanceof Error ? error.message : "Unknown image edit error";
          if (/monthly spending limit|spending limit|billing|quota/i.test(detail)) {
            throw new Error("当前 API Key 的图片编辑/生成额度已用尽。请前往代理商控制台提高或移除月度限额，或更换可用的 API Key。");
          }
          if (isTransientImageNetworkFailure(detail)) {
            throw new Error(buildTransientImageNetworkMessage(detail));
          }
          const summary = summarizeProviderImageFailure(detail, "edit");
          throw new Error(
            `当前 Provider 没有可用的真实图片生成或编辑端点。请前往“模型服务配置”页更换支持图片编辑的 Provider，或在规划页手动开启“允许 SVG 兜底预览”。原因摘要：${summary}`,
          );
        }

        const fallback = await generateSvgFallback({
          section,
          adapter,
          provider,
          assets,
          referenceAssets: productReferenceAssets,
          aspectRatio: sectionAspectRatio,
          contentLanguage: generationSettings.contentLanguage,
        });

        imageAsset = await assets.saveGeneratedImage({
          projectId,
          sectionId,
          prompt,
          source: {
            svgText: fallback.svgText,
            mimeType: "image/svg+xml",
          },
          metadata: {
            mode: "svg_fallback",
            usedModel: fallback.model,
            editMode,
            targetLanguage: editMode === "translate" ? effectiveContentLanguage : undefined,
            baseImageAssetId: section.currentImageAssetId,
            layout: fallback.layout,
            sourceReferenceAssetIds: productReferenceAssets.map((asset) => asset.id),
            primaryReferenceAssetId: productReferenceAssets[0]?.id ?? null,
            imageApiError: error instanceof Error ? error.message : "Unknown image edit api error",
          },
        });

        usedModel = fallback.model;
        generationMode = "svg_fallback";
      }

      version = await persistSectionVersion({
        sectionId,
        imageAssetId: imageAsset.id,
        promptSnapshot: prompt,
        copySnapshot: section.copy,
      });

      await repository.section.update(sectionId, {
        status: "SUCCESS",
        currentImageAssetId: imageAsset.id,
      });

      await repository.project.update(projectId, {
        status: "EDITING",
      });

      await tasks.completeTask(task.id, {
        mode: "edit_image",
        editMode,
        targetLanguage: editMode === "translate" ? effectiveContentLanguage : undefined,
        imageAssetId: imageAsset.id,
        versionId: version.id,
        usedModel,
        generationMode,
        baseImageAssetId: section.currentImageAssetId,
        sourceReferenceAssetIds: productReferenceAssets.map((asset) => asset.id),
      });

      return { imageAsset, version, usedModel, generationMode, editMode, targetLanguage: editMode === "translate" ? effectiveContentLanguage : undefined };
    } catch (error) {
      await repository.section.update(sectionId, {
        status: "FAILED",
      });

      await tasks.failTask(task.id, error instanceof Error ? error.message : "Image edit failed");
      throw error;
    }
  }

  return {
    generateSectionImage,
    regenerateSectionImage,
    editSectionImage,
    listSectionVersions,
    activateSectionVersion,
    persistSectionVersion,
  };
}
