function extractJsonBlock(raw: string) {
  const direct = raw.trim();
  if (direct.startsWith("{") || direct.startsWith("[")) {
    return direct;
  }

  const fencedMatch = direct.match(/```json([\s\S]*?)```/i) || direct.match(/```([\s\S]*?)```/i);
  if (fencedMatch?.[1]) {
    return fencedMatch[1].trim();
  }

  const firstBrace = direct.indexOf("{");
  const lastBrace = direct.lastIndexOf("}");
  if (firstBrace >= 0 && lastBrace > firstBrace) {
    return direct.slice(firstBrace, lastBrace + 1);
  }

  return direct;
}

function escapeXml(value: string) {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

/**
 * Upstream read the bytes off local disk; the port sources them through the
 * injected asset store (the driver owns the storage root).
 */
async function assetToDataUrl(assets: AssetStore, asset: Pick<AssetRecord, "filePath" | "mimeType">) {
  const buffer = await assets.readStorageFile(asset.filePath);
  const mimeType = asset.mimeType ?? "image/png";

  return `data:${mimeType};base64,${buffer.toString("base64")}`;
}

